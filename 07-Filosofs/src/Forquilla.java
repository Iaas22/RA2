public class Forquilla {
    private int numero;
    private boolean esta;

    public Forquilla(int numero) {
        this.numero = numero;
        this.esta = true;
    }

    public int getNumero() {
        return numero;
    }

    public void setNumero(int numero) {
        this.numero = numero;
    }

    public boolean isEsta() {
        return esta;
    }

    public void setEsta(boolean esta) {
        this.esta = esta;
    }
}
